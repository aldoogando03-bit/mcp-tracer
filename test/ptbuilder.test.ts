import { describe, expect, it } from "vitest";
import { generatePTBuilderScript, q } from "../src/ptbuilder.js";
import { Topology } from "../src/topology.js";
import { VERSION } from "../src/version.js";
import { codeOutsideStrings, runInPTBuilder } from "./helpers.js";

const STATEMENT = /^(addDevice|addLink|configureIosDevice|configurePcIp)\(.*\);$/;

/** Structural rules every generated script must follow (docs/PTBUILDER_API.md §1). */
function expectWellFormed(script: string) {
  const [header, ...statements] = script.split("\n");
  expect(header).toMatch(/^\/\*.*\*\/$/);
  expect(header.indexOf("*/")).toBe(header.length - 2);
  for (const line of statements) expect(line).toMatch(STATEMENT);
  expect(codeOutsideStrings(script)).not.toContain("//");
  expect(script).not.toContain("//");
  expect(script).not.toMatch(/[\u2028\u2029]/);
}

/** R1 - S1 - {PC1, PC2, SRV1} with explicit coordinates, IOS on R1/S1 and three host IP styles. */
function representative(): Topology {
  const t = new Topology();
  t.addDevice({ name: "R1", model: "2911", x: 300, y: 100 });
  t.addDevice({ name: "S1", model: "2960", x: 300, y: 250 });
  t.addDevice({ name: "PC1", model: "PC", x: 150, y: 400 });
  t.addDevice({ name: "PC2", model: "PC-PT", x: 300, y: 400 });
  t.addDevice({ name: "SRV1", model: "Server", x: 450, y: 400 });
  t.addLink({ dev1: "R1", port1: "Gi0/0", dev2: "S1", port2: "Gi0/1" });
  t.addLink({ dev1: "PC1", port1: "Fa0", dev2: "S1", port2: "Fa0/1" });
  t.addLink({ dev1: "PC2", port1: "FastEthernet0", dev2: "S1", port2: "FastEthernet0/2" });
  t.addLink({ dev1: "SRV1", port1: "fa0", dev2: "S1", port2: "fa0/3", cable: "straight" });
  t.configureIos({
    name: "R1",
    commands: ["enable", "configure terminal", "hostname R1", "interface GigabitEthernet0/0", "ip address 192.168.1.1 255.255.255.0", "no shutdown", "exit", "end", "write memory"],
  });
  t.configureIos({ name: "S1", commands: ["hostname S1"] });
  t.configurePc({ name: "PC1", ip: "192.168.1.10", mask: "255.255.255.0", gateway: "192.168.1.1", dns: "192.168.1.100" });
  t.configurePc({ name: "PC2", dhcp: true });
  t.configurePc({ name: "SRV1", ip: "192.168.1.100/24", gateway: "192.168.1.1" });
  return t;
}

describe("generatePTBuilderScript: structure", () => {
  it("starts with a /* */ header naming the version and has one ;-terminated statement per line", () => {
    const script = generatePTBuilderScript(representative());
    expectWellFormed(script);
    expect(script.split("\n")[0]).toBe(
      `/* Generated by mcp-tracer v${VERSION} - paste into Extensions > Builder Code Editor and click Run */`
    );
    expect(script.split("\n")).toHaveLength(1 + 5 + 4 + 2 + 3);
  });

  it("emits only the header for an empty topology, and it still runs", () => {
    const script = generatePTBuilderScript(new Topology());
    expect(script.split("\n")).toHaveLength(1);
    expectWellFormed(script);
    expect(runInPTBuilder(script)).toEqual([]);
  });

  it("emits devices, then links, then IOS configs, then host IPs", () => {
    const fns = generatePTBuilderScript(representative())
      .split("\n")
      .slice(1)
      .map((l) => l.slice(0, l.indexOf("(")));
    expect(fns).toEqual([
      ...Array(5).fill("addDevice"),
      ...Array(4).fill("addLink"),
      ...Array(2).fill("configureIosDevice"),
      ...Array(3).fill("configurePcIp"),
    ]);
  });
});

describe("generatePTBuilderScript: PTBuilder execution simulation", () => {
  it("makes exactly the expected calls for a representative topology", () => {
    const script = generatePTBuilderScript(representative());
    expect(runInPTBuilder(script)).toEqual([
      ["addDevice", "R1", "2911", 300, 100],
      ["addDevice", "S1", "2960-24TT", 300, 250],
      ["addDevice", "PC1", "PC-PT", 150, 400],
      ["addDevice", "PC2", "PC-PT", 300, 400],
      ["addDevice", "SRV1", "Server-PT", 450, 400],
      ["addLink", "R1", "GigabitEthernet0/0", "S1", "GigabitEthernet0/1", "straight"],
      ["addLink", "PC1", "FastEthernet0", "S1", "FastEthernet0/1", "straight"],
      ["addLink", "PC2", "FastEthernet0", "S1", "FastEthernet0/2", "straight"],
      ["addLink", "SRV1", "FastEthernet0", "S1", "FastEthernet0/3", "straight"],
      ["configureIosDevice", "R1", "hostname R1\ninterface GigabitEthernet0/0\nip address 192.168.1.1 255.255.255.0\nno shutdown\nexit"],
      ["configureIosDevice", "S1", "hostname S1"],
      ["configurePcIp", "PC1", false, "192.168.1.10", "255.255.255.0", "192.168.1.1", "192.168.1.100"],
      ["configurePcIp", "PC2", true],
      ["configurePcIp", "SRV1", false, "192.168.1.100", "255.255.255.0", "192.168.1.1", ""],
    ]);
  });

  it("passes adversarial names, ports and IOS commands through intact", () => {
    const names = {
      router: 'R"1\\x',
      sw: "S//1/*",
      pc: "PC*/1\u2028\u2029x",
      hub: "Hub ///\\// end",
      server: "line\nbreak\r'q'",
    };
    const t = new Topology();
    // addDevice rejects these names (DEVICE_NAME), so they are inserted directly: the generator must still quote them.
    expect(() => t.addDevice({ name: names.router, model: "2911" })).toThrow(/Invalid device name/);
    const put = (name: string, model: string, x: number) => t.devices.set(name, { name, model, x, y: 0 });
    put(names.router, "2911", 0);
    put(names.sw, "2960-24TT", 100);
    put(names.pc, "PC-PT", 200);
    // Hub-PT has no port data, so any port name is accepted and must survive verbatim.
    put(names.hub, "Hub-PT", 300);
    put(names.server, "Server-PT", 400);
    const hubPort1 = 'Port "0" // \u2028 */ \\';
    const hubPort2 = "Port 1//";
    t.addLink({ dev1: names.router, port1: "Gi0/0", dev2: names.sw, port2: "Gi0/1" });
    t.addLink({ dev1: names.pc, port1: "Fa0", dev2: names.hub, port2: hubPort1 });
    t.addLink({ dev1: names.server, port1: "Fa0", dev2: names.hub, port2: hubPort2 });
    t.configureIos({
      name: names.router,
      commands: [
        'description "quoted" \\ back // slash */ star',
        "interface GigabitEthernet0/0\r\n ip address 10.0.0.1 255.0.0.0\n\n no shutdown \nexit",
        "banner motd #http://x//y\u2028z#",
        "enable secret cisco",
      ],
    });
    t.configurePc({ name: names.pc, ip: "10.0.0.10/8", gateway: "10.0.0.1" });
    t.configurePc({ name: names.server, dhcp: true, dns: "10.0.0.53" });

    const script = generatePTBuilderScript(t);
    expectWellFormed(script);
    expect(runInPTBuilder(script)).toEqual([
      ["addDevice", names.router, "2911", 0, 0],
      ["addDevice", names.sw, "2960-24TT", 100, 0],
      ["addDevice", names.pc, "PC-PT", 200, 0],
      ["addDevice", names.hub, "Hub-PT", 300, 0],
      ["addDevice", names.server, "Server-PT", 400, 0],
      ["addLink", names.router, "GigabitEthernet0/0", names.sw, "GigabitEthernet0/1", "straight"],
      ["addLink", names.pc, "FastEthernet0", names.hub, hubPort1, "straight"],
      ["addLink", names.server, "FastEthernet0", names.hub, hubPort2, "straight"],
      [
        "configureIosDevice",
        names.router,
        [
          'description "quoted" \\ back // slash */ star',
          "interface GigabitEthernet0/0",
          "ip address 10.0.0.1 255.0.0.0",
          "no shutdown",
          "exit",
          "banner motd #http://x//y\u2028z#",
          "enable secret cisco",
        ].join("\n"),
      ],
      ["configurePcIp", names.pc, false, "10.0.0.10", "255.0.0.0", "10.0.0.1", ""],
      ["configurePcIp", names.server, true, "", "", "", "10.0.0.53"],
    ]);
  });

  it("still runs every statement when names contain what would otherwise end a comment or the line", () => {
    const t = new Topology();
    // "a//b" is a valid device name; the others can only come from a hand-built state, so they are inserted directly.
    t.addDevice({ name: "a//b", model: "PC-PT", x: 0, y: 0 });
    const tricky = ["a//b", "c*/d", "/*e", "f\\", "g\u2028h", "i\nj"];
    tricky.slice(1).forEach((name, i) => t.devices.set(name, { name, model: "PC-PT", x: i + 1, y: i + 1 }));
    const calls = runInPTBuilder(generatePTBuilderScript(t));
    expect(calls.map((c) => c[1])).toEqual(tricky);
  });
});

describe("generatePTBuilderScript: arguments", () => {
  it("joins IOS commands with \\n in one string and drops enable / conf t / end / wr", () => {
    const t = new Topology();
    t.addDevice({ name: "R1", model: "2911" });
    t.configureIos({ name: "R1", commands: ["en", "conf t", "hostname R1", "interface Gi0/0\nno shutdown", "End", "wr", "do wr mem", "copy run start"] });
    const line = generatePTBuilderScript(t).split("\n").find((l) => l.startsWith("configureIosDevice"));
    expect(line).toBe('configureIosDevice("R1", "hostname R1\\ninterface Gi0/0\\nno shutdown");');
  });

  it("drops the same lines from forged configs loaded through fromJSON", () => {
    const t = Topology.fromJSON({
      devices: [{ name: "R1", model: "2911" }],
      configs: { R1: ["enable", "configure terminal", "hostname R1", "end", "write memory"] },
    });
    expect(runInPTBuilder(generatePTBuilderScript(t))).toContainEqual(["configureIosDevice", "R1", "hostname R1"]);
  });

  it("does not emit configureIosDevice for a device whose commands were all replaced away", () => {
    const t = new Topology();
    t.addDevice({ name: "R1", model: "2911" });
    t.configureIos({ name: "R1", commands: ["hostname R1"] });
    t.configureIos({ name: "R1", commands: [], replace: true });
    expect(generatePTBuilderScript(t)).not.toContain("configureIosDevice");
  });

  it("uses the short DHCP form, and the full form only to pass a DNS server", () => {
    const t = new Topology();
    t.addDevice({ name: "PC1", model: "PC-PT" });
    t.addDevice({ name: "PC2", model: "PC-PT" });
    t.configurePc({ name: "PC1", dhcp: true, ip: "1.2.3.4", mask: "/8" });
    t.configurePc({ name: "PC2", dhcp: true, dns: "8.8.8.8" });
    const lines = generatePTBuilderScript(t).split("\n");
    expect(lines).toContain('configurePcIp("PC1", true);');
    expect(lines).toContain('configurePcIp("PC2", true, "", "", "", "8.8.8.8");');
  });

  it("configures hosts with a verified FastEthernet0 first, so an unverified one that throws cannot skip them", () => {
    const t = new Topology();
    const hosts = [["L1", "Laptop-PT"], ["PC1", "PC-PT"], ["P1", "Printer-PT"], ["SRV1", "Server-PT"], ["PC2", "PC-PT"]];
    for (const [name, model] of hosts) t.addDevice({ name, model });
    for (const [name] of hosts) t.configurePc({ name, dhcp: true });
    const order = runInPTBuilder(generatePTBuilderScript(t)).filter((c) => c[0] === "configurePcIp").map((c) => c[1]);
    // Verified (PC-PT, Server-PT) in insertion order, then unverified (Laptop-PT, Printer-PT) in insertion order.
    expect(order).toEqual(["PC1", "SRV1", "PC2", "L1", "P1"]);
  });

  it("passes every static field positionally, with empty strings for missing gateway and DNS", () => {
    const t = new Topology();
    t.addDevice({ name: "PC1", model: "PC-PT" });
    t.configurePc({ name: "PC1", ip: "192.168.1.10", mask: "/24" });
    expect(generatePTBuilderScript(t).split("\n")).toContain('configurePcIp("PC1", false, "192.168.1.10", "255.255.255.0", "", "");');
  });

  it("rounds coordinates to integers", () => {
    const t = new Topology();
    t.addDevice({ name: "A", model: "PC-PT", x: 10.4, y: 20.6 });
    t.addDevice({ name: "B", model: "PC-PT", x: -3.5, y: 1e-9 });
    const lines = generatePTBuilderScript(t).split("\n");
    expect(lines[1]).toBe('addDevice("A", "PC-PT", 10, 21);');
    expect(lines[2]).toBe('addDevice("B", "PC-PT", -3, 0);');
  });

  it("emits integer coordinates for auto-placed devices", () => {
    const t = representative();
    for (const d of t.devices.values()) {
      delete d.x;
      delete d.y;
    }
    for (const [, , , x, y] of runInPTBuilder(generatePTBuilderScript(t)).filter((c) => c[0] === "addDevice")) {
      expect(Number.isInteger(x)).toBe(true);
      expect(Number.isInteger(y)).toBe(true);
    }
  });

  it("emits the inferred cable when a link has none, and the explicit one otherwise", () => {
    const t = new Topology();
    t.addDevice({ name: "R1", model: "2911" });
    t.addDevice({ name: "R2", model: "2911" });
    t.addDevice({ name: "S1", model: "2960-24TT" });
    t.addLink({ dev1: "R1", port1: "Gi0/0", dev2: "R2", port2: "Gi0/0" });
    t.addLink({ dev1: "R1", port1: "Gi0/1", dev2: "S1", port2: "Gi0/1", cable: "cross" });
    const links = runInPTBuilder(generatePTBuilderScript(t)).filter((c) => c[0] === "addLink");
    expect(links.map((c) => c[5])).toEqual(["cross", "cross"]);
  });
});

describe("q()", () => {
  it.each([
    ["plain", '"plain"'],
    ['a"b', '"a\\"b"'],
    ["a\\b", '"a\\\\b"'],
    ["a/b", '"a/b"'],
    ["a//b", '"a\\/\\/b"'],
    ["///", '"\\/\\/\\/"'],
    ["\u2028\u2029", '"\\u2028\\u2029"'],
    ["a\nb", '"a\\nb"'],
  ])("quotes %j as %s", (input, expected) => {
    expect(q(input)).toBe(expected);
    expect(JSON.parse(q(input))).toBe(input);
    expect(new Function(`return ${q(input)};`)()).toBe(input);
  });
});
