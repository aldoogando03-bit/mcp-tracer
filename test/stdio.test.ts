/**
 * Smoke test of the built stdio server (build/index.js). Skipped when build/ is missing: run `npm run build`
 * first (CI builds before testing).
 */
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { makeTempDir } from "./helpers.js";

const ENTRY = fileURLToPath(new URL("../build/index.js", import.meta.url));
const HAS_BUILD = existsSync(ENTRY);
const TIMEOUT = 30_000;
const STARTUP_LOG = /^\[mcp-tracer\] info: v\S+ running on stdio$/m;

async function waitFor(condition: () => boolean, what: string, ms = 10_000): Promise<void> {
  const start = Date.now();
  while (!condition()) {
    if (Date.now() - start > ms) throw new Error(`Timed out after ${ms} ms waiting for ${what}`);
    await new Promise((r) => setTimeout(r, 25));
  }
}

describe.skipIf(!HAS_BUILD)(
  HAS_BUILD ? "stdio server (build/index.js)" : "stdio server: SKIPPED because build/index.js does not exist (run npm run build)",
  () => {
    let dir: string;
    let cleanup: () => Promise<void>;

    beforeEach(async () => {
      ({ dir, cleanup } = await makeTempDir());
    });

    afterEach(async () => {
      await cleanup();
    });

    it(
      "serves the tools over StdioClientTransport, writes only JSON-RPC to stdout and logs to stderr",
      async () => {
        const transport = new StdioClientTransport({
          command: process.execPath,
          args: [ENTRY],
          cwd: dir,
          env: { MCP_TRACER_DIR: dir },
          stderr: "pipe",
        });
        let stderr = "";
        transport.stderr!.on("data", (chunk: Buffer) => (stderr += chunk.toString("utf8")));
        const client = new Client({ name: "mcp-tracer-stdio-test", version: "0.0.0" });
        // Any stdout line that is not a JSON-RPC message makes the SDK's ReadBuffer throw, reported here.
        const transportErrors: Error[] = [];
        client.onerror = (e) => transportErrors.push(e);

        try {
          await client.connect(transport);
          expect(client.getServerVersion()?.name).toBe("mcp-tracer");

          const { tools } = await client.listTools();
          expect(tools).toHaveLength(15);

          const r = (await client.callTool({ name: "add_device", arguments: { name: "R1", model: "4331" } })) as CallToolResult;
          expect(r.isError).toBeFalsy();
          expect(r.content[0]).toMatchObject({ type: "text", text: expect.stringMatching(/^Added R1: ISR4331 \(resolved from "4331"\)/) });

          const script = (await client.callTool({ name: "generate_script", arguments: {} })) as CallToolResult;
          expect(script.content[0]).toMatchObject({ type: "text", text: expect.stringMatching(/^\/\* Generated by mcp-tracer/) });

          await waitFor(() => STARTUP_LOG.test(stderr), "the startup log on stderr");
          expect(transportErrors).toEqual([]);
        } finally {
          await client.close();
        }
      },
      TIMEOUT
    );

    it(
      "answers raw JSON-RPC with one JSON message per stdout line and exits when stdin closes",
      async () => {
        const child = spawn(process.execPath, [ENTRY], { cwd: dir, stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
        let stdout = "";
        let stderr = "";
        child.stdout.on("data", (c: Buffer) => (stdout += c.toString("utf8")));
        child.stderr.on("data", (c: Buffer) => (stderr += c.toString("utf8")));
        const exited = new Promise<number | null>((resolve) => child.on("close", (code) => resolve(code)));

        const send = (msg: object) => child.stdin.write(`${JSON.stringify(msg)}\n`);
        send({
          jsonrpc: "2.0",
          id: 1,
          method: "initialize",
          params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "raw", version: "0" } },
        });
        send({ jsonrpc: "2.0", method: "notifications/initialized" });
        send({ jsonrpc: "2.0", id: 2, method: "tools/list" });
        send({ jsonrpc: "2.0", id: 3, method: "tools/call", params: { name: "validate_config", arguments: {} } });

        try {
          await waitFor(() => stdout.split("\n").filter(Boolean).length >= 3, "three responses on stdout");
        } finally {
          child.stdin.end();
        }
        const code = await Promise.race([exited, new Promise<"timeout">((r) => setTimeout(() => r("timeout"), 10_000))]);
        if (code === "timeout") child.kill();
        expect(code).toBe(0);

        expect(stdout.endsWith("\n")).toBe(true);
        const messages = stdout
          .split("\n")
          .filter(Boolean)
          .map((line) => JSON.parse(line) as { jsonrpc: string; id: number; result?: Record<string, unknown> });
        expect(messages.map((m) => [m.jsonrpc, m.id])).toEqual([["2.0", 1], ["2.0", 2], ["2.0", 3]]);
        expect((messages[1].result!.tools as unknown[]).length).toBe(15);
        expect(JSON.stringify(messages[2].result)).toContain("EMPTY_TOPOLOGY");
        expect(stderr).toMatch(STARTUP_LOG);
      },
      TIMEOUT
    );
  }
);
