/**
 * PTBuilder script generator. Pure, no MCP imports or I/O. Rules (docs/PTBUILDER_API.md §1-§2): the editor
 * strips every newline before running, so never emit `//` and end every statement with `;`.
 */
import { resolveCable } from "./cables.js";
import { findPort, getModelInfo } from "./catalog.js";
import { layoutPositions } from "./layout.js";
import type { PcIp, Topology } from "./topology.js";
import { VERSION } from "./version.js";

/**
 * Safe JS string literal: JSON.stringify, plus U+2028/U+2029 escaped (pre-ES2019 engines) and every slash
 * of a "//" run escaped, so the script never contains "//" even inside strings.
 */
export const q = (s: string) =>
  JSON.stringify(s)
    .replaceAll(String.fromCharCode(0x2028), "\\u2028")
    .replaceAll(String.fromCharCode(0x2029), "\\u2029")
    .replace(/\/{2,}/g, (m) => m.replace(/\//g, "\\/"));

const int = (n: number) => {
  if (!Number.isFinite(n)) throw new Error(`Cannot emit non-finite coordinate ${n}.`);
  return String(Math.round(n));
};

/** Builds the script to paste into Packet Tracer: Extensions > Builder Code Editor > Run. */
export function generatePTBuilderScript(t: Topology): string {
  const version = VERSION.replace(/[^\w.+-]/g, "");
  const out: string[] = [`/* Generated by mcp-tracer v${version} - paste into Extensions > Builder Code Editor and click Run */`];

  const pos = layoutPositions(t);
  for (const d of t.devices.values()) {
    const p = pos.get(d.name) ?? { x: 0, y: 0 };
    out.push(`addDevice(${q(d.name)}, ${q(d.model)}, ${int(p.x)}, ${int(p.y)});`);
  }
  for (const l of t.links) {
    out.push(`addLink(${q(l.dev1)}, ${q(l.port1)}, ${q(l.dev2)}, ${q(l.port2)}, ${q(resolveCable(t, l))});`);
  }
  for (const [name, cmds] of t.configs) {
    if (cmds.length) out.push(`configureIosDevice(${q(name)}, ${q(cmds.join("\n"))});`);
  }
  // Hosts whose FastEthernet0 is verified (PC-PT, Server-PT) first: a configurePcIp that throws on an unverified
  // model (Laptop-PT, Printer-PT...) aborts the rest of the script, so it must not skip the verified ones.
  const verified = (p: PcIp) => {
    const d = t.devices.get(p.name);
    return !!d && findPort(getModelInfo(d.model), "FastEthernet0")?.verified === true;
  };
  const pcs = [...t.pcIps.values()];
  for (const p of [...pcs.filter(verified), ...pcs.filter((p) => !verified(p))]) {
    if (p.dhcp) {
      out.push(p.dns ? `configurePcIp(${q(p.name)}, true, "", "", "", ${q(p.dns)});` : `configurePcIp(${q(p.name)}, true);`);
    } else {
      const args = [p.ip, p.mask, p.gateway, p.dns].map((v) => q(v ?? "")).join(", ");
      out.push(`configurePcIp(${q(p.name)}, false, ${args});`);
    }
  }
  return out.join("\n");
}
